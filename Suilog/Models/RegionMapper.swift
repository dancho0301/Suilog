//
//  配信データの地域名をアプリが使う7地域に正規化するマッパー。
//  aquariums.json v21以降は region が都道府県名のため、
//  地域フィルタ・統計・バッジが使う7地域へ変換する。
//

import Foundation

enum RegionMapper {
    /// アプリの地域フィルタ・統計が使う7地域
    static let validRegions: Set<String> = [
        "北海道", "東北", "関東", "中部", "近畿", "中国・四国", "九州・沖縄"
    ]

    /// 都道府県名 → 7地域 の対応表
    private static let prefectureToRegion: [String: String] = [
        // 北海道
        "北海道": "北海道",
        // 東北
        "青森県": "東北", "岩手県": "東北", "宮城県": "東北",
        "秋田県": "東北", "山形県": "東北", "福島県": "東北",
        // 関東
        "茨城県": "関東", "栃木県": "関東", "群馬県": "関東",
        "埼玉県": "関東", "千葉県": "関東", "東京都": "関東", "神奈川県": "関東",
        // 中部
        "新潟県": "中部", "富山県": "中部", "石川県": "中部",
        "福井県": "中部", "山梨県": "中部", "長野県": "中部",
        "岐阜県": "中部", "静岡県": "中部", "愛知県": "中部",
        // 近畿
        "三重県": "近畿", "滋賀県": "近畿", "京都府": "近畿",
        "大阪府": "近畿", "兵庫県": "近畿", "奈良県": "近畿", "和歌山県": "近畿",
        // 中国・四国
        "鳥取県": "中国・四国", "島根県": "中国・四国", "岡山県": "中国・四国",
        "広島県": "中国・四国", "山口県": "中国・四国",
        "徳島県": "中国・四国", "香川県": "中国・四国",
        "愛媛県": "中国・四国", "高知県": "中国・四国",
        // 九州・沖縄
        "福岡県": "九州・沖縄", "佐賀県": "九州・沖縄", "長崎県": "九州・沖縄",
        "熊本県": "九州・沖縄", "大分県": "九州・沖縄", "宮崎県": "九州・沖縄",
        "鹿児島県": "九州・沖縄", "沖縄県": "九州・沖縄"
    ]

    /// 地域名を7地域に正規化する
    /// - 7地域名ならそのまま返す（従来形式の後方互換）
    /// - 都道府県名なら対応する地域に変換する（v21形式対応）
    /// - どちらでもない場合はそのまま返す
    static func normalize(_ region: String) -> String {
        if validRegions.contains(region) {
            return region
        }
        return prefectureToRegion[region] ?? region
    }
}
